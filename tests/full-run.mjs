import { createRequire } from 'module'; const require = createRequire(import.meta.url); const { chromium } = require('playwright');
import path from 'path';
const URL_ = process.argv[2]; const dir = process.argv[5] || '/tmp';
const W = 640, Hh = 400;
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: W, height: Hh } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('console', m => { if (m.type() === 'error' && !m.text().includes('ERR_FAILED')) errors.push(m.text()); });
  page.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
  await page.route('**/*', r => { const u = r.request().url(); if (u.startsWith(URL_)) return r.continue(); return r.abort(); });
  await page.goto(URL_);
  await page.waitForTimeout(1000);
  const G = (fn) => page.evaluate(fn);
  const waitFor = async (fn, ms) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (await page.evaluate(fn)) return true; await page.waitForTimeout(100); } return false; };
  const fps = await G(() => new Promise(res => { let n = 0; const t0 = performance.now(); const f = () => { n++; if (performance.now() - t0 < 1000) requestAnimationFrame(f); else res(n); }; requestAnimationFrame(f); }));
  console.log('fps', fps);
  await page.keyboard.press('KeyX');
  console.log('state after key', await G(() => window.__gato.state), 'buttons', (await G(() => window.__gato.menuButtons())).length);
  await G(() => window.__gato.startRun(['kitchen', 'bedroom', 'living']));
  console.log('state', await G(() => window.__gato.state + ' ' + window.__gato.level.key));
  // KITCHEN
  await G(() => { const [a, b] = window.__gato.cats; a.pos.x = 11; a.pos.y = 1.0; a.pos.z = 1.25; b.pos.x = 2.5; b.pos.y = 0; b.pos.z = 10.95; });
  await page.waitForTimeout(300);
  await page.keyboard.press('KeyE');
  await page.keyboard.press('Slash');
  console.log('kitchen solved', await waitFor(() => window.__gato.level.isSolved(), 3000));
  console.log('gate opens', await waitFor(() => window.__gato.level.gates[0].open > 0.9, 15000));
  await G(() => { const [a, b] = window.__gato.cats; b.pos.x = 16; b.pos.y = 0; b.pos.z = 9; });
  await page.waitForTimeout(500);
  await G(() => { const [a, b] = window.__gato.cats; a.pos.x = 16.5; a.pos.y = 0; a.pos.z = 1.4; b.pos.x = 18.3; b.pos.y = 0; b.pos.z = 1.6; });
  console.log('to blessing', await waitFor(() => window.__gato.state === 'blessing', 20000), 'bank', await G(() => window.__gato.save.bank));
  await page.screenshot({ path: path.join(dir, 's_bless.png') });
  console.log('blessings offered', JSON.stringify(await G(() => window.__gato.menuButtons())));
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(400);
  console.log('state', await G(() => window.__gato.state + ' ' + window.__gato.level.key + ' ' + window.__gato.run.blessings.join(',')));
  // BEDROOM
  await G(() => { const [a, b] = window.__gato.cats; a.pos.x = 5.2; a.pos.y = 0; a.pos.z = 9.6; b.pos.x = 7.3; b.pos.y = 0.15; b.pos.z = 1.1; });
  console.log('lift up with cat', await waitFor(() => window.__gato.level.lift.y > 2.55, 30000), JSON.stringify(await G(() => window.__gato.cats[1].pos)));
  await page.screenshot({ path: path.join(dir, 's_bed.png') });
  await G(() => { const [a, b] = window.__gato.cats; b.pos.x = 11.0; b.pos.y = 2.6; b.pos.z = 0.7; });
  await page.waitForTimeout(300);
  await page.keyboard.press('Slash');
  console.log('switched', await waitFor(() => window.__gato.level.isSolved(), 3000));
  console.log('drawers solid', await waitFor(() => window.__gato.level.solids.filter(s => s.name === 'drawer').every(s => s.active), 20000));
  await G(() => { const a = window.__gato.cats[0]; a.pos.x = 13.2; a.pos.y = 2.2; a.pos.z = 2.4; a.vel.y = 0; });
  await page.waitForTimeout(1500);
  console.log('cat0 lands on low drawer (0.65)', JSON.stringify(await G(() => window.__gato.cats[0].pos)));
  await page.screenshot({ path: path.join(dir, 's_bed2.png') });
  await G(() => { const [a, b] = window.__gato.cats; a.pos.x = 9.4; a.pos.y = 2.6; a.pos.z = 1.0; b.pos.x = 10.9; b.pos.y = 2.6; b.pos.z = 1.2; });
  console.log('to blessing 2', await waitFor(() => window.__gato.state === 'blessing', 20000));
  await page.keyboard.press('Enter');
  await page.waitForTimeout(400);
  console.log('state', await G(() => window.__gato.state + ' ' + window.__gato.level.key + ' ' + window.__gato.run.blessings.join(',') + ' mods ' + JSON.stringify(window.__gato.mods)));
  // LIVING: straight to the tree top
  await G(() => { const [a, b] = window.__gato.cats; a.pos.x = 20.8; a.pos.y = 1.9; a.pos.z = 2.8; b.pos.x = 21.8; b.pos.y = 1.9; b.pos.z = 3.3; });
  console.log('to nap', await waitFor(() => window.__gato.state === 'nap', 20000), JSON.stringify(await G(() => window.__gato.save)));
  await page.screenshot({ path: path.join(dir, 's_nap.png') });
  await page.keyboard.press('Enter');
  await page.waitForTimeout(300);
  console.log('state', await G(() => window.__gato.state));
  await G(() => { window.__gato.save.bank = 12; });
  await page.click('#opt-0-coat-tuxedo'); await page.waitForTimeout(100);
  await page.click('#opt-1-hat-party'); await page.waitForTimeout(100);
  await page.click('#opt-0-hat-party'); await page.waitForTimeout(100);
  console.log('after buys', JSON.stringify(await G(() => window.__gato.save)));
  await page.screenshot({ path: path.join(dir, 's_hub.png') });
  await page.reload(); await page.waitForTimeout(800);
  console.log('after reload bank', await G(() => window.__gato.save.bank), JSON.stringify(await G(() => window.__gato.save.wear)));
  await page.keyboard.press('KeyX');
  await G(() => window.__gato.startRun(['living', 'kitchen', 'bedroom']));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(dir, 's_dressed.png') });
  console.log('errors', JSON.stringify(errors));
  await browser.close();
})();
